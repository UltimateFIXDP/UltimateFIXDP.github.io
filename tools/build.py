#!/usr/bin/env python3
# Builds index.html and i18n.js of the site: python3 build.py <site folder>
# base.py holds the features, engine fixes, credits and screenshots; extra.py the other sections; template.html the page.
import json, os, re, sys, html

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1]
g = {'__name__': 'site', 'sys': sys}
exec(open(os.path.join(HERE, 'base.py'), encoding='utf-8').read(), g)
exec(open(os.path.join(HERE, 'extra.py'), encoding='utf-8').read(), g)
T = g['T']

for name in ('features', 'engine', 'credits', 'shots'):  # reveal on scroll, the lightbox for the screenshots
    v = g[name]
    v = v.replace('class="glass-card feature">', 'class="glass-card feature reveal">')
    v = v.replace('class="glass-card feature engine">', 'class="glass-card feature engine reveal">')
    v = v.replace('class="shot glass-card">', 'class="shot glass-card reveal">')
    v = v.replace('class="glass-card credit"', 'class="glass-card credit reveal"')
    v = v.replace('target="_blank" rel="noopener"><img', 'class="zoom"><img')
    g[name] = v

desc = ("UltimateFIXDP: the all-in-one fix for Deadly Premonition: The Director's Cut. One DLL: stability, 45 to 180 FPS, "
        "real resolution, HBAO, SMAA, Xbox 360 look, DualSense, full map, mod manager, photo mode. Ukrainian + English.")
ld = {"@context": "https://schema.org", "@type": "SoftwareApplication", "name": "UltimateFIXDP", "description": desc,
      "applicationCategory": "GameApplication", "operatingSystem": "Windows", "url": g['SITE'],
      "downloadUrl": g['REPO'] + "/releases/latest", "softwareVersion": "0.7.9", "license": "https://opensource.org/licenses/MIT",
      "offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD"},
      "author": {"@type": "Person", "name": "Dmytro Bidlov", "url": "https://t.me/LittleBitUA"}, "inLanguage": ["uk", "en"]}

page = open(os.path.join(HERE, 'template.html'), encoding='utf-8').read()
subs = {'desc': html.escape(desc), 'site': g['SITE'], 'repo': g['REPO'], 'ldjson': json.dumps(ld, ensure_ascii=False),
        'gh': g['GH'], 'tg': g['TG'], 'yt': g['YT'], 'st': g['ST'], 'stats': g['stats'], 'news': g['news'], 'before': g['before'],
        'features': g['features'], 'engine': g['engine'], 'shots': g['shots'], 'credits': g['credits'], 'tree': g['tree'],
        'keys': g['keys'], 'faq': g['faq'], 'stats2': g['stats2'], 'compare': g['compare'], 'news2': g['news2'], 'menu_tabs': g['menu_tabs'], 'menu_panels': g['menu_panels']}
for k, v in subs.items():
    page = page.replace('{{' + k + '}}', v)
left = re.findall(r'\{\{\w+\}\}', page)
assert not left, left

# empty elements of the template get their English text, so the page reads without scripts too
def fill(m):
    key = m.group(2)
    assert key in T, key
    return m.group(1) + T[key][0] + m.group(3)
page = re.sub(r'(<[a-z0-9]+[^>]*data-i18n(?:-html)?="([^"]+)"[^>]*>)(</)', fill, page)
missing = [k for k in re.findall(r'data-i18n(?:-html)?="([^"]+)"', page) if k not in T]
assert not missing, missing

open(os.path.join(OUT, 'index.html'), 'w', encoding='utf-8').write(page)
tables = {'en': {k: v[0] for k, v in T.items()}, 'uk': {k: v[1] for k, v in T.items()}}
open(os.path.join(OUT, 'i18n.js'), 'w', encoding='utf-8').write(
    "// Site localization: UA / EN (generated by tools/build.py)\n'use strict';\nwindow.SITE_I18N = "
    + json.dumps(tables, ensure_ascii=False, indent=1) + ";\n")
print('ok:', len(T), 'texts')
